def build_scenario_data_table(
    position: CreditPosition,
) -> list[dict[str, str]]:
    """Build the display table for a CreditPosition without rendering it."""
    rows = []

    for field in fields(position):
        field_name = field.name
        value = getattr(position, field_name)

        rows.append(
            {
                "Financial Indicator": format_field_label(field_name),
                "Value": format_field_value(field_name, value),
                "Unit": get_field_unit(field_name),
                "Description": format_field_description(field_name),
            }
        )

    return rows


