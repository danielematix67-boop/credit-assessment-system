def format_field_value(field_name: str, value: Any) -> str:
    """Format a field value for display without changing its underlying value."""
    if value is None:
        return "Not available"

    if field_name == "position_id":
        return str(value)

    if field_name in PERCENTAGE_FIELDS:
        return f"{float(value):.1%}"

    if field_name in CURRENCY_FIELDS:
        return f"€{float(value):,.0f}"

    if field_name == "nfp_to_ebitda":
        return f"{float(value):.2f}x"

    if isinstance(value, float):
        return f"{value:,.4f}"

    return str(getattr(value, "value", value))


