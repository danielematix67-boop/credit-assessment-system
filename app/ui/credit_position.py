def build_scenario_data_table(
    position: CreditPosition,
) -> list[dict[str, str]]:

    rows = []

    for field in fields(position):

        field_name = field.name

        value = getattr(
            position,
            field_name,
        )

        rows.append(
            {
                "Financial Indicator": format_field_label(
                    field_name
                ),
                "Value": format_field_value(
                    field_name,
                    value,
                ),
                "Unit": get_field_unit(
                    field_name
                ),
                "Description": format_field_description(
                    field_name
                ),
            }
        )

    return rows


def display_position_table(
    position: CreditPosition,
) -> None:

    position_data = build_scenario_data_table(
        position
    )

    st.dataframe(
        position_data,
        width="stretch",
        hide_index=True,
        column_config={
            "Financial Indicator": st.column_config.TextColumn(
                "Financial Indicator",
                width="medium",
            ),
            "Value": st.column_config.TextColumn(
                "Value",
                width="medium",
            ),
            "Unit": st.column_config.TextColumn(
                "Unit",
                width="small",
            ),
            "Description": st.column_config.TextColumn(
                "What it represents",
                width="large",
            ),
        },
    )


