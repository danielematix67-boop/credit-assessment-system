def format_field_label(
    field_name: str,
) -> str:

    special_terms = {
        "ebitda": "EBITDA",
        "nfp": "NFP",
        "id": "ID",
    }

    words = field_name.split("_")

    formatted_words = []

    for word in words:

        if word.lower() in special_terms:

            formatted_words.append(
                special_terms[word.lower()]
            )

        else:

            formatted_words.append(
                word.capitalize()
            )

    return " ".join(formatted_words)


