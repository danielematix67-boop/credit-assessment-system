def create_optional_numeric_field(
    field_name: str,
    label: str,
    resolved_type: Any,
    default: Any,
) -> Any:

    provided_key = (
        f"credit_position_{field_name}_provided"
    )

    value_key = (
        f"credit_position_{field_name}_value"
    )

    provided = st.checkbox(
        f"Provide {label}",
        value=default is not None,
        key=provided_key,
    )

    if not provided:
        return None

    if resolved_type is int:

        value = st.number_input(
            label,
            value=(
                int(default)
                if default is not None
                else 0
            ),
            step=1,
            key=value_key,
        )

        _render_field_metadata(
            description=format_field_description(
                field_name
            ),
            unit=get_field_unit(
                field_name
            ),
        )

        return value

    if resolved_type is float:

        value = st.number_input(
            label,
            value=(
                float(default)
                if default is not None
                else 0.0
            ),
            step=0.01,
            format="%.4f",
            key=value_key,
        )

        _render_field_metadata(
            description=format_field_description(
                field_name
            ),
            unit=get_field_unit(
                field_name
            ),
        )

        return value

    raise TypeError(
        f"Unsupported optional numeric type: "
        f"{field_name} -> {resolved_type}"
    )


def create_streamlit_field(
    field,
    field_type: Any,
) -> Any:

    field_name = field.name

    label = format_field_label(
        field_name
    )

    default = get_field_default(
        field
    )

    resolved_type, is_optional = (
        unwrap_optional(field_type)
    )

    description = format_field_description(
        field_name
    )

    unit = get_field_unit(
        field_name
    )

    # --------------------------------------------------------
    # String
    # --------------------------------------------------------

    if resolved_type is str and not is_optional:

        value = st.text_input(
            label,
            value=(
                ""
                if default is None
                else str(default)
            ),
            key=f"credit_position_{field_name}",
        )

        _render_field_metadata(
            description=description,
            unit=unit,
        )

        return value

    # --------------------------------------------------------
    # Optional String
    # --------------------------------------------------------

    if resolved_type is str and is_optional:

        provided = st.checkbox(
            f"Provide {label}",
            value=default is not None,
            key=(
                f"credit_position_{field_name}_provided"
            ),
        )

        if not provided:
            return None

        value = st.text_input(
            label,
            value=(
                ""
                if default is None
                else str(default)
            ),
            key=(
                f"credit_position_{field_name}_value"
            ),
        )

        _render_field_metadata(
            description=description,
            unit=unit,
        )

        return value

    # --------------------------------------------------------
    # Required Integer
    # --------------------------------------------------------

    if resolved_type is int and not is_optional:

        value = st.number_input(
            label,
            value=(
                0
                if default is None
                else int(default)
            ),
            step=1,
            key=f"credit_position_{field_name}",
        )

        _render_field_metadata(
            description=description,
            unit=unit,
        )

        return value

    # --------------------------------------------------------
    # Required Float
    # --------------------------------------------------------

    if resolved_type is float and not is_optional:

        value = st.number_input(
            label,
            value=(
                0.0
                if default is None
                else float(default)
            ),
            step=0.01,
            format="%.4f",
            key=f"credit_position_{field_name}",
        )

        _render_field_metadata(
            description=description,
            unit=unit,
        )

        return value

    # --------------------------------------------------------
    # Optional Numeric
    # --------------------------------------------------------

    if (
        is_optional
        and resolved_type in {int, float}
    ):

        return create_optional_numeric_field(
            field_name=field_name,
            label=label,
            resolved_type=resolved_type,
            default=default,
        )

    raise TypeError(
        f"Unsupported CreditPosition field type: "
        f"{field_name} -> {field_type}"
    )


