def _render_field_metadata(
    *,
    description: str,
    unit: str,
) -> None:
    """
    Render compact metadata below an input field.
    """

    if unit:

        st.caption(
            f"{description} · Unit: {unit}"
        )

    else:

        st.caption(
            description
        )


